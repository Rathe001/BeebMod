--[[ scripts/make-sexes.lua (Josh 2026-10-03): which model files are a man's
and which a woman's.

A MAN OR A WOMAN, FROM THE MODEL (Josh 2026-10-03: "could we add male/female
icons to switch between male/female models (if they exist)?"). An enemy drawn
from a playable race's model is a man in one drawing and a woman in the next:
the game picks one of the creature's looks each time a model is drawn. A model
says which file it drew (GetModelFileID), and the community listfile names the
file: character/human/female/humanfemale.m2 is a woman's, whatever the enemy
is called. This reads the listfile and writes Modules/Expedition/SexData.lua:
every model file in a race's male or female folder, and every creature model
whose name ends in "male" or "female" (creature/naga/nagafemale.m2), with the
game's own number for its sex (2 a man, 3 a woman, as UnitSex says them).

Run from the repo root:

    curl -L -o listfile.csv https://github.com/wowdev/wow-listfile/releases/latest/download/community-listfile.csv
    lua scripts/make-sexes.lua listfile.csv

The listfile is about 150 MB and not kept in the repo.
]]

local listfile = assert(arg[1], "usage: lua scripts/make-sexes.lua <community-listfile.csv>")
local MALE, FEMALE = 2, 3

local out, n = {}, 0
for line in io.lines(listfile) do
	local id, path = line:match("^(%d+);(.+)$")
	if id then
		path = path:lower()
		local sex
		-- character/<race>/<male|female>/<anything>.m2
		local folder = path:match("^character/[^/]+/(%a+)/[^/]+%.m2$")
		if folder == "male" then
			sex = MALE
		elseif folder == "female" then
			sex = FEMALE
		else
			-- creature/<folder>/<name>male.m2 and <name>female.m2
			local name = path:match("^creature/[^/]+/([^/]+)%.m2$")
			if name then
				if name:match("female$") then
					sex = FEMALE
				elseif name:match("male$") then
					sex = MALE
				end
			end
		end
		if sex then
			out[#out + 1] = { tonumber(id), sex, path }
			n = n + 1
		end
	end
end
table.sort(out, function(a, b) return a[1] < b[1] end)

local f = assert(io.open("Modules/Expedition/SexData.lua", "wb"))
f:write("-- Which model files are a man's (2) and which a woman's (3), as UnitSex\n")
f:write("-- numbers them: by the model's folder or name in the community listfile\n")
f:write("-- (https://github.com/wowdev/wow-listfile).\n")
f:write(("-- GENERATED by scripts/make-sexes.lua on %s; do not edit.\n"):format(os.date("%Y-%m-%d")))
f:write("local _, BT = ...\n")
f:write("BT.ExpeditionSexes = {\n")
for _, e in ipairs(out) do
	f:write(("\t[%d] = %d, -- %s\n"):format(e[1], e[2], e[3]))
end
f:write("}\n")
f:close()
print(("wrote Modules/Expedition/SexData.lua: %d model files"):format(n))
