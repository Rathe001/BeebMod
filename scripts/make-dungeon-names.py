# Builds Modules/Expedition/DungeonData.lua: what each dungeon and raid enemy
# is, by its npc id, from the VMaNGOS world database
# (https://github.com/vmangos/core, GPL-2.0). Inside a dungeon the game hides
# an enemy's name and GUID from addons, so a kill counted from its loot went
# in the journal as "#3653" (2026-11-11, audit). The journal fills the name,
# type, rank and levels in from here (Modules/Expedition/Journal.lua, J.Fill).
#
#   gh release download db_latest -R vmangos/core -p "db-sqlite-*.zip"
#   unzip db-sqlite-*.zip
#   python scripts/make-dungeon-names.py sqlite-dump/mangos.sqlite
#
# An enemy is listed when it has a spawn on a dungeon or raid map (creature,
# map_template.map_type 1 or 2). One a script summons mid-fight has no spawn
# and is not listed. The dungeons new in Forever are not in this database.
import sqlite3
import sys
from datetime import date

DUNGEON, RAID = 1, 2
# creature_template.type and .rank, as the game says them
TYPES = {1: "Beast", 2: "Dragonkin", 3: "Demon", 4: "Elemental", 5: "Giant", 6: "Undead",
         7: "Humanoid", 8: "Critter", 9: "Mechanical"}
RANKS = {1: "elite", 2: "rareelite", 3: "worldboss", 4: "rare"}

db = sqlite3.connect(sys.argv[1])

kinds = {}
for entry, map_type in db.execute("select entry, map_type from map_template order by patch"):
    kinds[entry] = map_type

# the latest row of each creature (one per patch)
creatures = {}
for row in db.execute("select entry, name, level_min, level_max, type, rank from creature_template order by patch"):
    creatures[row[0]] = row[1:]

inside = {}
for row in db.execute("select id, id2, id3, id4, id5, map from creature"):
    kind = kinds.get(row[5])
    if kind in (DUNGEON, RAID):
        for npc in row[:5]:
            if npc:
                # a raid's word wins where an enemy stands in both
                inside[npc] = "raid" if kind == RAID or inside.get(npc) == "raid" else "party"

lines = [
    "-- What each dungeon and raid enemy is, by its npc id: from the VMaNGOS world",
    "-- database (https://github.com/vmangos/core), under the GPL 2.0 licence.",
    "-- { name, creature type, rank, lowest level, highest level, \"party\" or \"raid\" }",
    f"-- GENERATED by scripts/make-dungeon-names.py on {date.today().isoformat()}; do not edit.",
    "local _, BT = ...",
    "BT.ExpeditionDungeon = {",
]
n = 0
for npc in sorted(inside):
    c = creatures.get(npc)
    if not c:
        continue
    name, lo, hi, kind, rank = c
    # triggers, bunnies and the like have no name a player sees
    if not name or "trigger" in name.lower() or "bunny" in name.lower() or "DND" in name or kind in (10, 11, 12):
        continue
    name = name.replace("\\", "\\\\").replace('"', '\\"')
    t = '"%s"' % TYPES[kind] if kind in TYPES else "nil"
    r = '"%s"' % RANKS[rank] if rank in RANKS else "nil"
    lines.append('\t[%d] = { "%s", %s, %s, %d, %d, "%s" },' % (npc, name, t, r, lo, hi, inside[npc]))
    n += 1
lines.append("}")

with open("Modules/Expedition/DungeonData.lua", "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"{n} enemies written")
