# Builds Modules/Tooltips/QuestDropData.lua: which enemies drop each quest item,
# by the item's name, from the VMaNGOS world database
# (https://github.com/vmangos/core, GPL-2.0).
#
#   gh release download db_latest -R vmangos/core -p "db-sqlite-*.zip"
#   unzip db-sqlite-*.zip
#   python scripts/make-quest-drops.py sqlite-dump/mangos.sqlite
#
# Josh 2026-11-09: "This quest is showing all crabs dropping the quest item in
# the tooltip." The enemy tooltip guessed by name: "crab" in Fine Crab Chunks
# matched every crab. The database says only Reef Crawlers and Encrusted Tide
# Crawlers drop them.
#
# An item is kept when a quest asks for it and it is a quest item, or an enemy
# drops it only while you have the quest. Its enemies are every creature whose
# loot table holds it. A quest item no enemy drops is kept with no enemies,
# so the tooltip never guesses for it: the Webwood Egg comes from a nest.
# Common items a quest also asks for, such as cloth, are left out.
import sqlite3
import sys
from datetime import date

QUEST_CLASS = 12

db = sqlite3.connect(sys.argv[1])

wanted = set()
for row in db.execute("select ReqItemId1, ReqItemId2, ReqItemId3, ReqItemId4 from quest_template"):
    wanted.update(x for x in row if x)

# the latest row of each item and creature (both have one per patch)
items = {}
for entry, name, cls in db.execute("select entry, name, class from item_template order by patch"):
    items[entry] = (name, cls)
by_loot = {}
for entry, loot_id in db.execute("select entry, loot_id from creature_template order by patch"):
    if loot_id:
        by_loot.setdefault(loot_id, set()).add(entry)

drops = {}
for loot_id, item, chance, ref in db.execute(
        "select entry, item, ChanceOrQuestChance, mincountOrRef from creature_loot_template"):
    if ref < 0 or item not in wanted or item not in items:
        continue
    if chance < 0 or items[item][1] == QUEST_CLASS:
        drops.setdefault(item, set()).update(by_loot.get(loot_id, ()))

# by name, as the quest log writes the objective; two items of one name share
by_name = {}
for item in wanted:
    if item not in items:
        continue
    name, cls = items[item]
    if item in drops or cls == QUEST_CLASS:
        by_name.setdefault(name.lower(), set()).update(drops.get(item, ()))


def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = [
    "-- Which enemies drop each quest item, by its name in lower case: from the",
    "-- VMaNGOS world database (https://github.com/vmangos/core), under the GPL 2.0",
    "-- licence. An empty list is a quest item no enemy drops.",
    f"-- GENERATED by scripts/make-quest-drops.py on {date.today().isoformat()}; do not edit.",
    "local _, BT = ...",
    "BT.QuestDrops = {",
]
for name in sorted(by_name):
    npcs = ", ".join(str(n) for n in sorted(by_name[name]))
    out.append(f"\t[{lua(name)}] = {{ {npcs} }}," if npcs else f"\t[{lua(name)}] = {{}},")
out.append("}")
with open("Modules/Tooltips/QuestDropData.lua", "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print(len(by_name), "items,", sum(1 for v in by_name.values() if v), "dropped by enemies,",
      sum(len(v) for v in by_name.values()), "pairs")
